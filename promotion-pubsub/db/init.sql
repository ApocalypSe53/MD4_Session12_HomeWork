-- Schema dùng chung (chạy tự động khi container Postgres khởi tạo lần đầu; test chạy trên H2).
-- products   : do product-service sở hữu
-- promotions : do promotion-service sở hữu, product-service chỉ đọc để tính giá bán

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT PRIMARY KEY,
    name        VARCHAR(255)   NOT NULL,
    base_price  NUMERIC(15, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS promotions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT         NOT NULL UNIQUE REFERENCES products (id),
    sale_price  NUMERIC(15, 2) NOT NULL,
    active      BOOLEAN        NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

